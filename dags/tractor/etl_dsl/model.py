class EtlDslSchema(BaseModel):
    """Base class for the ETL DSL schema."""

    pass


class CommandDetailed(BaseModel):
    """Detailed command model.

    Attributes:
        operator_type (str): The type of operator to be used.
        command (str): The command to be executed.
    """

    operator_type: str = Field(
        ...,
        description="The type of operator to be used. See https://airflow.apache.org/docs/apache-airflow/stable/_api/airflow/operators/index.html for more information.",
    )
    command: str = Field(..., description="The command to be executed.")
    image: Optional[str] = Field(
        None, description="The image to be used for the command."
    )


# Define the class as a union of the two types, a string that will be expanded, or the details
Command = RootModel[Union[str, CommandDetailed]]


