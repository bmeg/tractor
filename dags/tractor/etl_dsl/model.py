class StorageObjectDetailed(BaseModel):
    """Detailed storage object model.

    Attributes:
        url (Optional[str]): The URL of the storage object.
        path (str): The path of the storage object.
        type (Optional[Type]): The type of the storage object.
        name (Optional[str]): The name of the storage object.
        description (Optional[str]): The description of the storage object.
    """

    url: Optional[str] = Field(None, description="The URL of the storage object.")
    path: str = Field(..., description="The path of the storage object.")

    type: Optional[str] = Field(
        "FILE",
        pattern="^(FILE|DIRECTORY)$",
        description="The type of the storage object.",
    )

    name: Optional[str] = Field(None, description="The name of the storage object.")
    description: Optional[str] = Field(
        None, description="The description of the storage object."
    )

    def to_tes_input(self) -> tes.Input:
        """Convert the StorageObject model to a tes.Input object."""
        return tes.Input(
            url=self.url,
            path=self.path,
            type=self.type,
            name=self.name,
            description=self.description,
        )

    def to_tes_output(self) -> tes.Output:
        """Convert the StorageObject model to a tes.Input object."""
        return tes.Output(
            url=self.url,
            path=self.path,
            type=self.type,
            name=self.name,
            description=self.description,
        )


